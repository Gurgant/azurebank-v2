    public AccountServiceTests()
    {
        /*
          `InMemoryTestModelCustomizer` is what lets these tests exist at all. Every CreateAccount
          test in this region used to carry
          `[Fact(Skip = "Requires SQL Server - RowVersion is auto-generated by DB")]`, which was
          never true: the customizer strips `byte[]` concurrency tokens, so InMemory has nothing to
          generate. Three of the four passed unchanged the moment the attribute came off.

          The database is NAMED and given an explicit root so a test can open a SECOND context over
          the same store — the only way to prove a write actually persisted rather than merely
          sitting in this context's change tracker.
        */
        var options = new DbContextOptionsBuilder<AzureBankDbContext>()
            .UseInMemoryDatabase(_databaseName, _databaseRoot)
            .ReplaceService<IModelCustomizer, InMemoryTestModelCustomizer>()
            .Options;

        _context = new AzureBankDbContext(options);
        _accountAccessMock = new Mock<IAccountAccessService>();
        _mapper = new AccountMapper();
        _loggerMock = new Mock<ILogger<AccountService>>();

        _sut = new AccountService(
            _context,
            _accountAccessMock.Object,
            _mapper,
            _loggerMock.Object);
    }

    public void Dispose()
