    [Fact]
    public async Task CreateAccountAsync_ReturnsADistinctMaskedNumberEachTime()
    {
        /*
          This test was skipped as "Requires SQL Server - RowVersion", and neither half of that was
          the problem. Un-skipping it failed outright:

            Expected result.AccountNumber to match regex "^AB-\d{4}-\d{4}-\d{2}$",
            but "AB-****-****-81" does not match.

          It asserted the RAW number on a field the API masks by default (ADR-0020, applied in
          `AccountMapper.MaskAccountNumber`). The skip is why nobody noticed a test contradicting a
          shipped decision — a disabled test cannot report drift.

          The name was wrong too: it said "unique" while the body created ONE account and compared
          nothing. Both halves are asserted now, because the masked suffix is the only part a caller
          sees and two accounts sharing one is exactly the collision worth catching.
        */
        var userId = Guid.NewGuid();
        var first = await _sut.CreateAccountAsync(
            userId, new CreateAccountRequest { Name = "First", Type = AccountType.Checking });
        var second = await _sut.CreateAccountAsync(
            userId, new CreateAccountRequest { Name = "Second", Type = AccountType.Savings });

        first.AccountNumber.Should().MatchRegex(@"^AB-\*{4}-\*{4}-\d{2}$");
        second.AccountNumber.Should().MatchRegex(@"^AB-\*{4}-\*{4}-\d{2}$");

        // The RAW numbers must differ. Asserted on the entities, since the wire only ever shows the
        // last two digits and two different accounts can legitimately share those.
        var stored = await _context.Accounts.Where(a => a.UserId == userId).ToListAsync();
        stored.Should().HaveCount(2);
        stored.Select(a => a.AccountNumber).Distinct().Should().HaveCount(2);
        stored.Should().AllSatisfy(a => a.AccountNumber.Should().MatchRegex(@"^AB-\d{4}-\d{4}-\d{2}$"),
            "the DB keeps the real number; only the response is masked");
    }

    [Fact]
    public async Task CreateAccountAsync_PersistsAccountToDatabase()
    {
        // Arrange
        var userId = Guid.NewGuid();
        var request = new CreateAccountRequest
        {
            Name = "Persisted Account",
            Type = AccountType.Checking
        };

        // Act
        var result = await _sut.CreateAccountAsync(userId, request);

        /*
          Re-read on a SECOND context over the same store, which is the whole point of the test.

          The original asserted through `_context.Accounts.FindAsync`, and `FindAsync` returns a
          tracked entity without going to the database — so it would have passed with the
          `SaveChangesAsync` inside `CreateAccountAsync` deleted. A persistence test that cannot
          fail when persistence is removed is not testing persistence.

          Proven by mutation, not by argument: commenting out that SaveChanges leaves the old
          assertion green and this one red.
        */
        await using var freshContext = new AzureBankDbContext(
            new DbContextOptionsBuilder<AzureBankDbContext>()
                .UseInMemoryDatabase(_databaseName, _databaseRoot)
                .ReplaceService<IModelCustomizer, InMemoryTestModelCustomizer>()
                .Options);

        var savedAccount = await freshContext.Accounts.SingleOrDefaultAsync(a => a.Id == result.Id);
        savedAccount.Should().NotBeNull();
        savedAccount!.Name.Should().Be("Persisted Account");
        savedAccount.UserId.Should().Be(userId, "the row must be owned by the caller, not just exist");
        savedAccount.Balance.Should().Be(0);
    }

